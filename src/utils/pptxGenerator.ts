import PptxGenJS from "pptxgenjs";
import type { SlideDeckData } from "../types/meetmind";

function sanitizeFilename(title: string): string {
  const base = (title || "meetmind_deck")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
  return `${base || "meetmind_deck"}.pptx`;
}

function buildPptxInstance(deck: SlideDeckData): PptxGenJS {
  const pptx = new PptxGenJS();
  pptx.layout = "LAYOUT_16x9";
  pptx.author = "MeetMind";
  pptx.title = deck.deckTitle;
  pptx.subject = deck.subtitle || "Meeting Summary & Action Plan";

  const slides = deck.slides && deck.slides.length > 0 ? deck.slides : [];

  slides.forEach((slideData, idx) => {
    const slide = pptx.addSlide();
    slide.background = { color: "071318" };

    // Top glacial teal accent bar
    slide.addShape(pptx.ShapeType.rect, {
      x: 0,
      y: 0,
      w: 10,
      h: 0.1,
      fill: { color: "5EEAD4" },
    });

    // Slide index pill
    slide.addText(`SLIDE ${idx + 1} / ${slides.length}  ·  ${slideData.layout.toUpperCase()}`, {
      x: 0.65,
      y: 0.35,
      w: 8.7,
      h: 0.3,
      fontSize: 10,
      bold: true,
      color: "5EEAD4",
      fontFace: "Arial",
    });

    if (idx === 0 || slideData.layout === "title") {
      slide.addText(slideData.title || deck.deckTitle, {
        x: 0.65,
        y: 1.55,
        w: 8.7,
        h: 1.3,
        fontSize: 32,
        bold: true,
        color: "ECF4F6",
        fontFace: "Arial",
      });
      if (slideData.subtitle || deck.subtitle) {
        slide.addText(slideData.subtitle || deck.subtitle, {
          x: 0.65,
          y: 2.95,
          w: 8.5,
          h: 0.7,
          fontSize: 16,
          color: "99F6E4",
          fontFace: "Arial",
        });
      }
      if (slideData.bullets.length > 0) {
        slide.addText(
          slideData.bullets.map((b) => ({
            text: b,
            options: { bullet: true, breakLine: true },
          })),
          {
            x: 0.65,
            y: 3.8,
            w: 8.5,
            h: 1.3,
            fontSize: 14,
            color: "CBD5E1",
            fontFace: "Arial",
            valign: "top",
          }
        );
      }
    } else {
      slide.addText(slideData.title, {
        x: 0.65,
        y: 0.72,
        w: 8.7,
        h: 0.75,
        fontSize: 24,
        bold: true,
        color: "ECF4F6",
        fontFace: "Arial",
      });

      if (slideData.subtitle) {
        slide.addText(slideData.subtitle, {
          x: 0.65,
          y: 1.45,
          w: 8.7,
          h: 0.4,
          fontSize: 13,
          color: "94A3B8",
          fontFace: "Arial",
        });
      }

      // Subtle card container
      slide.addShape(pptx.ShapeType.roundRect, {
        x: 0.6,
        y: 1.95,
        w: 8.8,
        h: 3.15,
        fill: { color: "0D2129" },
        line: { color: "1E4B56", width: 1 },
      });

      const bullets = slideData.bullets.length > 0 ? slideData.bullets : ["No items recorded."];
      slide.addText(
        bullets.map((b) => ({
          text: b,
          options: { bullet: true, breakLine: true },
        })),
        {
          x: 0.85,
          y: 2.15,
          w: 8.3,
          h: 2.8,
          fontSize: 15,
          color: "E2F1F5",
          fontFace: "Arial",
          lineSpacingMultiple: 1.3,
          valign: "top",
        }
      );
    }

    // Footer
    slide.addText("Generated by MeetMind", {
      x: 0.65,
      y: 5.25,
      w: 5.0,
      h: 0.25,
      fontSize: 9,
      color: "64748B",
      fontFace: "Arial",
    });

    if (slideData.speakerNotes) {
      slide.addNotes(slideData.speakerNotes);
    }
  });

  return pptx;
}

export async function generatePptxBlob(deck: SlideDeckData): Promise<{
  blob: Blob;
  filename: string;
}> {
  const pptx = buildPptxInstance(deck);
  const filename = sanitizeFilename(deck.deckTitle);
  const out = (await pptx.write({ outputType: "blob" })) as Blob;
  return { blob: out, filename };
}

export async function generatePptxBase64(deck: SlideDeckData): Promise<{
  base64Data: string;
  filename: string;
  mimeType: string;
}> {
  const pptx = buildPptxInstance(deck);
  const filename = sanitizeFilename(deck.deckTitle);
  const base64Data = (await pptx.write({ outputType: "base64" })) as string;
  return {
    base64Data,
    filename,
    mimeType:
      "application/vnd.openxmlformats-officedocument.presentationml.presentation",
  };
}

export async function triggerPptxDownload(deck: SlideDeckData): Promise<string> {
  const { blob, filename } = await generatePptxBlob(deck);
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  window.setTimeout(() => URL.revokeObjectURL(url), 4000);
  return filename;
}
